package com.example.data.datasource.mediastore

import android.content.ContentValues
import android.content.Context
import android.graphics.Bitmap
import android.net.Uri
import android.os.Build
import android.os.Environment
import android.provider.MediaStore
import com.example.domain.repository.IMediaStoreExporter
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream
import java.io.OutputStream

class MediaStoreExporter(private val context: Context) : IMediaStoreExporter {

    override suspend fun exportToDeviceGallery(
        bitmap: Bitmap,
        title: String
    ): Result<String> = withContext(Dispatchers.IO) {
        val fileName = "Lumina_${System.currentTimeMillis()}"
        val resolver = context.contentResolver

        val values = ContentValues().apply {
            put(MediaStore.Images.Media.DISPLAY_NAME, "$fileName.png")
            put(MediaStore.Images.Media.MIME_TYPE, "image/png")
            put(MediaStore.Images.Media.TITLE, title.take(50))
            put(MediaStore.Images.Media.DESCRIPTION, "Generated by Lumina AI: $title")
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                put(MediaStore.Images.Media.RELATIVE_PATH, Environment.DIRECTORY_PICTURES + "/LuminaAI")
                put(MediaStore.Images.Media.IS_PENDING, 1)
            }
        }

        val uri: Uri? = resolver.insert(MediaStore.Images.Media.EXTERNAL_CONTENT_URI, values)
        if (uri == null) {
            return@withContext Result.failure(IllegalStateException("Could not create MediaStore entry"))
        }

        try {
            val outputStream: OutputStream? = resolver.openOutputStream(uri)
            outputStream?.use { out ->
                val success = bitmap.compress(Bitmap.CompressFormat.PNG, 100, out)
                if (!success) {
                    throw IllegalStateException("Failed to compress bitmap into MediaStore output stream")
                }
            } ?: throw IllegalStateException("Could not open output stream for MediaStore")

            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                values.clear()
                values.put(MediaStore.Images.Media.IS_PENDING, 0)
                resolver.update(uri, values, null, null)
            }
            Result.success(uri.toString())
        } catch (e: Exception) {
            resolver.delete(uri, null, null)
            Result.failure(e)
        }
    }
}
